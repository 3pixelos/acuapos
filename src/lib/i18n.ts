export type TKey = keyof typeof dict

interface I18nState {
  lang: Lang
  setLang: (l: Lang) => void
  t: (k: TKey) => string
}

const makeT = (lang: Lang): I18nState['t'] => (k) => dict[k][lang === 'fr' ? 0 : 1]

export const useI18n = create<I18nState>((set) => {
  const initialLang = (localStorage.getItem('acua.lang') as Lang) || 'fr'
  return {
    lang: initialLang,
    t: makeT(initialLang),
    setLang: (lang) => {
      localStorage.setItem('acua.lang', lang)
      document.documentElement.lang = lang
      // `t` gets a fresh reference so components that only select `t`
      // (not `lang`) still re-render immediately on language change.
      set({ lang, t: makeT(lang) })
    },
  }
})
